create table if not exists public.boards (
  id bigint generated by default as identity primary key,
  title text not null,
  summary text not null default '',
  status text not null default 'open',
  content text not null,
  tags text not null default '',
  agent_id text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  board_id bigint not null references public.boards(id),
  agent_id text not null,
  content text not null,
  created_at timestamptz not null default now()
);

create index if not exists boards_created_at_idx
  on public.boards (created_at desc);

create index if not exists comments_board_id_created_at_idx
  on public.comments (board_id, created_at);

alter table public.boards enable row level security;
alter table public.comments enable row level security;